def build_manifest(raw_dir: str, out_csv: str) -> None:
    """Walk datasets/raw/ and write a flat manifest.csv from RAW_LABEL_MAP.

    Any raw subfolder not present in RAW_LABEL_MAP is skipped with a warning
    printed to stdout — this is intentional, it forces you to explicitly
    classify every new dataset you add rather than silently mislabeling it.
    """
    rows = []
    skipped = set()
    for dirpath, _, filenames in os.walk(raw_dir):
        rel = os.path.relpath(dirpath, raw_dir).replace("\\", "/")
        if rel not in RAW_LABEL_MAP:
            if filenames:
                skipped.add(rel)
            continue
        crop, cause, deficiency = RAW_LABEL_MAP[rel]
        for fn in filenames:
            if not fn.lower().endswith((".jpg", ".jpeg", ".png")):
                continue
            rows.append({
                "image_path": os.path.join(dirpath, fn),
                "crop": crop,
                "cause": cause,
                "deficiency_class": deficiency or "n/a",
                "severity": "unlabeled",  # filled in later by weak labeling, see severity.py
            })

    with open(out_csv, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=[
            "image_path", "crop", "cause", "deficiency_class", "severity"])
        writer.writeheader()
        writer.writerows(rows)

    print(f"Wrote {len(rows)} rows to {out_csv}")
    if skipped:
        print(f"Skipped {len(skipped)} unmapped folders — add them to "
              f"RAW_LABEL_MAP in dataset.py:")
        for s in sorted(skipped):
            print(f"  {s}")


@dataclass
class Sample:
    image_path: str
    crop: str
    cause: str
    deficiency_class: str
    severity: str


class ExplainCropDataset(Dataset):
    """Reads manifest.csv and serves (image, crop_idx, cause_idx, npk_idx, severity_idx)."""

    def __init__(self, manifest_csv: str, split: str = "train",
                 image_size: int = CFG.image_size):
        self.samples: List[Sample] = []
        with open(manifest_csv) as f:
            for row in csv.DictReader(f):
                self.samples.append(Sample(**row))

        mean, std = [0.485, 0.456, 0.406], [0.229, 0.224, 0.225]
        if split == "train":
            self.transform = T.Compose([
                T.RandomResizedCrop(image_size, scale=(0.8, 1.0)),
                T.RandomHorizontalFlip(),
                T.RandomRotation(15),
                T.ColorJitter(brightness=0.2, contrast=0.2, saturation=0.2),
                T.ToTensor(),
                T.Normalize(mean, std),
            ])
        else:
            self.transform = T.Compose([
                T.Resize((image_size, image_size)),
                T.ToTensor(),
                T.Normalize(mean, std),
            ])

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int):
        s = self.samples[idx]
        img = Image.open(s.image_path).convert("RGB")
        img = self.transform(img)

        crop_idx = CROP_TO_IDX[s.crop]
        cause_idx = CAUSE_CLASSES.index(s.cause)
        npk_idx = (NPK_CLASSES.index(s.deficiency_class)
                   if s.deficiency_class in NPK_CLASSES else -100)  # ignore_index
        sev_idx = (SEVERITY_LEVELS.index(s.severity)
                   if s.severity in SEVERITY_LEVELS else -100)

        return img, crop_idx, cause_idx, npk_idx, sev_idx


